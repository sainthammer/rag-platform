"""Абстрактный интерфейс для сервисов эмбеддингов.

Модуль задаёт единый контракт для всех провайдеров векторизации:
OpenAI, SentenceTransformers и тестовых реализаций. Остальной код
должен зависеть от ``EmbeddingService``, а не от конкретного SDK.
"""

from abc import ABC, abstractmethod


class EmbeddingService(ABC):
    """Базовый класс для всех сервисов построения эмбеддингов.

    Любая реализация должна уметь векторизовать один текст, батч текстов
    и сообщать размерность вектора текущей модели.
    """

    @abstractmethod
    def embed(self, text: str) -> list[float]:
        """Построить эмбеддинг для одного текста."""
        ...

    @abstractmethod
    def embed_batch(self, texts: list[str]) -> list[list[float]]:
        """Построить эмбеддинги для списка текстов.

        Порядок выходных векторов должен совпадать с порядком входных строк.
        """
        ...

    @abstractmethod
    def dimension(self) -> int:
        """Вернуть размерность вектора."""
        ...
