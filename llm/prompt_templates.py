"""Шаблоны системных промптов для RAG-пайплайна.

Каждый шаблон — неизменяемый объект ``PromptTemplate``, который:
  1. Хранит текст системного промпта с плейсхолдером ``{context}``.
  2. При необходимости добавляет «суфлёрскую» инструкцию к сообщению
     пользователя через ``user_prefix``.

Шаблоны подбираются под разные сценарии:
  - ``BASE``         — универсальный, разрешает добавлять факты из памяти.
  - ``STRICT``       — только по контексту, никакой «галлюцинации».
  - ``CITATION``     — ответ с цитатами [1], [2] и списком источников.
  - ``MULTILINGUAL`` — модель определяет язык вопроса и отвечает на нём.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class PromptTemplate:
    """Неизменяемый шаблон системного промпта.

    ``frozen=True`` гарантирует, что экземпляры (BASE, STRICT и т.д.) не могут
    быть случайно изменены в рантайме — шаблоны используются как константы.

    Attributes:
        system: Текст системного промпта. Должен содержать плейсхолдер
            ``{context}``, который ``format_system`` заменит на реальный
            контекст из векторного хранилища.
        user_prefix: Дополнительная инструкция, которая добавляется перед
            текстом запроса пользователя. Пустая строка — инструкция не нужна.
    """

    system: str
    user_prefix: str = ""  # пустой — инструкция для пользователя не нужна

    def format_system(self, context: str) -> str:
        """Подставить контекст в системный промпт.

        Args:
            context: Текст, сформированный из найденных чанков (через
                ``TokenBudgetManager.fit_chunks``).

        Returns:
            Готовый системный промпт с вставленным контекстом.
        """
        return self.system.format(context=context)

    def format_user(self, query: str) -> str:
        """Сформировать финальное сообщение пользователя.

        Если задан ``user_prefix`` — он добавляется перед запросом, чтобы
        «напомнить» модели ограничения прямо в user-туре (это усиливает
        эффект по сравнению с только системным промптом).

        Args:
            query: Исходный вопрос пользователя.

        Returns:
            Сообщение пользователя (с префиксом или без).
        """
        if self.user_prefix:
            # Разделяем инструкцию и вопрос пустой строкой для лучшей
            # читаемости модели.
            return f"{self.user_prefix}\n\n{query}"
        return query


# ---------------------------------------------------------------------------
# Готовые шаблоны
# ---------------------------------------------------------------------------

BASE = PromptTemplate(
    system="""\
Ты полезный ассистент. Отвечай на вопрос пользователя, используя приведённый ниже контекст.
Если контекст не содержит достаточной информации — честно скажи об этом.
ВАЖНО: отвечай ТОЛЬКО на русском языке, используя ТОЛЬКО кириллические буквы.
Категорически запрещено использовать латиницу, арабский, китайский или любые другие символы внутри русских слов.
Каждое слово ответа должно быть написано полностью кириллицей.

Контекст:
{context}
""",
)
"""Базовый шаблон — подходит для большинства задач."""

STRICT = PromptTemplate(
    system="""\
Ты точный ассистент. Отвечай ТОЛЬКО на основе приведённого ниже контекста.
НЕ используй внешние знания и не делай выводов, которых нет в контексте.
Если ответ не найден в контексте, ответь:
«У меня недостаточно информации, чтобы ответить на этот вопрос.»
Отвечай на том же языке, на котором задан вопрос.

Контекст:
{context}
""",
    # user_prefix дублирует ограничение в user-туре: повторение инструкции
    # в разных ролях снижает вероятность галлюцинаций.
    user_prefix="Отвечай строго по контексту. Не придумывай.",
)
"""Строгий шаблон — только по контексту, без домысливания."""

CITATION = PromptTemplate(
    system="""\
Ты ассистент-исследователь. Отвечай на вопрос пользователя, используя приведённый ниже контекст.
Каждое утверждение сопровождай ссылкой на источник в квадратных скобках, например [1], [2].
В конце ответа приведи список использованных фрагментов под заголовком «Источники:».
Если контекст не содержит ответа — скажи об этом.
Отвечай на том же языке, на котором задан вопрос.

Контекст:
{context}
""",
    user_prefix="Приведи ссылки на источники для каждого утверждения.",
)
"""Шаблон с цитированием — каждое утверждение сопровождается ссылкой [N]."""

MULTILINGUAL = PromptTemplate(
    system="""\
Ты многоязычный ассистент. Определи язык вопроса пользователя и отвечай на том же языке.
Используй приведённый ниже контекст для ответа.
Если контекст не содержит нужной информации — скажи об этом на том же языке.

Контекст:
{context}
""",
)
"""Многоязычный шаблон — модель определяет язык вопроса и отвечает на нём."""

# Реестр всех шаблонов для доступа по имени (используется в get_template).
TEMPLATES: dict[str, PromptTemplate] = {
    "base": BASE,
    "strict": STRICT,
    "citation": CITATION,
    "multilingual": MULTILINGUAL,
}


def get_template(name: str) -> PromptTemplate:
    """Получить шаблон по строковому имени.

    Удобно при конфигурировании через env-переменную или аргумент CLI —
    не нужно импортировать константы напрямую.

    Args:
        name: Ключ из ``TEMPLATES`` (``"base"``, ``"strict"``, ``"citation"``,
            ``"multilingual"``).

    Returns:
        Соответствующий ``PromptTemplate``.

    Raises:
        ValueError: Если имя не найдено в реестре.
    """
    try:
        return TEMPLATES[name]
    except KeyError:
        # Сообщаем список допустимых имён, чтобы ошибка была самодокументирующей.
        raise ValueError(f"Unknown template {name!r}. Available: {list(TEMPLATES)}")
