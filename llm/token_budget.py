"""Управление токенным бюджетом для контекстного окна модели.

Каждая языковая модель имеет ограниченное контекстное окно (context window).
``TokenBudgetManager`` считает токены через tiktoken и выбирает максимальный
набор чанков, который вмещается в отведённый бюджет, не позволяя запросу
выйти за пределы окна модели.

Устройство бюджета:
    total window
    ├── reserved_tokens  — системный промпт + вопрос + ожидаемый ответ
    └── budget           — оставшееся место под контекст из чанков
"""

import tiktoken

# Размеры контекстных окон популярных моделей (в токенах).
# Используются как потолок, если вызывающий код не задал max_context_tokens.
_CONTEXT_WINDOWS: dict[str, int] = {
    "gpt-4o": 128_000,
    "gpt-4o-mini": 128_000,
    "gpt-4-turbo": 128_000,
    "gpt-4": 8_192,
    "gpt-3.5-turbo": 16_385,
    "claude-opus-4-8": 200_000,
    "claude-sonnet-4-6": 200_000,
    "claude-haiku-4-5-20251001": 200_000,
}

# Консервативный запасной вариант для моделей не из списка (например, Ollama).
_FALLBACK_WINDOW = 8_192


class TokenBudgetManager:
    """Подбирает набор чанков, вмещающийся в токенный бюджет.

    Args:
        model: Имя модели для tiktoken. Используется двояко:
            1. для выбора BPE-токенизатора (тот же, что у целевой модели);
            2. для определения размера контекстного окна по умолчанию.
        max_context_tokens: Явный потолок токенов. Если ``None`` — берётся
            из ``_CONTEXT_WINDOWS`` для данной модели (или ``_FALLBACK_WINDOW``).
        reserved_tokens: Число токенов, зарезервированных для системного
            промпта, вопроса и ожидаемого ответа. Вычитается из окна,
            чтобы контекст не вытеснял их.
    """

    def __init__(
        self,
        model: str = "gpt-4o",
        max_context_tokens: int | None = None,
        reserved_tokens: int = 1_000,
    ) -> None:
        try:
            # Пытаемся взять точный энкодер для модели — он учитывает
            # специфику BPE токенизатора (cl100k_base, o200k_base и т.д.).
            self._enc = tiktoken.encoding_for_model(model)
        except Exception:
            # Для Ollama-моделей, неизвестных имён и сетевых ошибок при
            # скачивании tiktoken-файла — универсальный энкодер.
            self._enc = tiktoken.get_encoding("cl100k_base")

        # Определяем размер окна: явный аргумент → таблица → запасной вариант.
        window = _CONTEXT_WINDOWS.get(model, _FALLBACK_WINDOW)
        # Итоговый бюджет: сколько токенов можно отдать под контекст.
        self.budget = (max_context_tokens or window) - reserved_tokens

    def count(self, text: str) -> int:
        """Подсчитать число токенов в строке.

        Args:
            text: Произвольный текст.

        Returns:
            Количество токенов согласно BPE-энкодеру выбранной модели.
        """
        return len(self._enc.encode(text))

    def fit_chunks(self, chunks: list[str]) -> list[str]:
        """Вернуть наибольший префикс *chunks*, умещающийся в бюджет.

        Чанки обрабатываются в исходном порядке (предполагается, что они
        отсортированы по релевантности). Как только очередной чанк не
        помещается — итерация прекращается, чтобы не пропускать более
        релевантные чанки в пользу менее релевантных.

        Args:
            chunks: Список текстовых фрагментов (обычно результат vector search).

        Returns:
            Подсписок чанков, суммарно не превышающих ``self.budget`` токенов.
        """
        selected: list[str] = []
        used = 0  # накопленное число токенов уже принятых чанков

        for chunk in chunks:
            tokens = self.count(chunk)
            if used + tokens > self.budget:
                # Чанк не влезает — прекращаем, чтобы не нарушить порядок
                # релевантности пропуском этого чанка.
                break
            selected.append(chunk)
            used += tokens

        return selected

    def remaining(self, chunks: list[str]) -> int:
        """Число токенов, оставшихся в бюджете после размещения *chunks*.

        Полезно для диагностики: позволяет понять, насколько плотно заполнен
        контекст и не теряются ли чанки из-за переполнения бюджета.

        Args:
            chunks: Список чанков, которые предполагается использовать.

        Returns:
            Остаток токенного бюджета (>= 0).
        """
        # Считаем только те чанки, которые fit_chunks реально примет.
        used = sum(self.count(c) for c in self.fit_chunks(chunks))
        # max(0, …) защищает от отрицательного остатка при некорректных входных данных.
        return max(0, self.budget - used)
